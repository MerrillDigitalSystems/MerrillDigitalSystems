/**
 * Emits the nginx 301 map from a single source, so the two places a redirect
 * could live can never disagree. Run as part of `npm run build`.
 *
 * Every rule is a SINGLE hop: old .html path -> new extensionless path. The
 * legacy pretty-URL redirects that used to point at .html files are rewritten
 * to point straight at their final destination, so no visitor and no crawler
 * ever traverses a chain.
 */
import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
// Written inside site/ so the Docker build stage produces it too — stage 2
// copies it out of the builder rather than trusting a host-generated file.
