/**
 * Routes that are new in the rebuild and never had a legacy .html URL.
 *
 * They still need a rule: the static export writes out/pricing.html, and
 * nginx's `try_files $uri $uri.html` will happily serve that file when asked
 * for /pricing.html — so without this, every new page answers on two URLs.
 * Canonicals would eventually sort it out, but publishing duplicates and
 * relying on Google to pick is not the same as not publishing them.
 *
 * /404.html is deliberately absent: it is wired to `error_page` and an exact
 * -match redirect on it would break the error page.
 */
const NEW_HTML = [
  "/pricing.html",
  "/privacy.html",
  "/web-design-west-jordan.html",
  "/work/ccl-pro.html",
  "/work/bays-baked-goods.html",
];

/** Pretty URLs the old nginx/Netlify config already served. */
const LEGACY_PRETTY = [
  ["/privacy/primis", "/privacy-primis"],
  ["/privacy/ops-hub", "/privacy-bookkeeping-os"],
];

const rules = [
  ...[...LEGACY_HTML, ...NEW_HTML].map((from) => [
    from,
    from === "/index.html" ? "/" : from.replace(/\.html$/, ""),
  ]),
  ...LEGACY_PRETTY,
];

// Guard against a rule whose destination is itself another rule's source —
// that would produce a redirect chain, which bleeds link equity.
const sources = new Set(rules.map(([from]) => from));
const chained = rules.filter(([, to]) => sources.has(to));
if (chained.length) {
  console.error("Redirect chain detected:", chained);
  process.exit(1);
}

const conf = [
  "# GENERATED by site/scripts/generate-redirects.mjs - do not edit by hand.",
  "# Included from nginx.conf. Every rule is a single 301 hop.",
  "",
  ...rules.map(([from, to]) => `location = ${from} { return 301 ${to}; }`),
  "",
].join("\n");

const outPath = resolve(siteRoot, "redirects-mds.conf");
const previous = (() => {
  try {
    return readFileSync(outPath, "utf8");
  } catch {
    return null;
  }
})();

if (previous !== conf) {
  writeFileSync(outPath, conf, "utf8");
  console.log(`redirects-mds.conf written — ${rules.length} rules`);
} else {
  console.log(`redirects-mds.conf unchanged — ${rules.length} rules`);
}
